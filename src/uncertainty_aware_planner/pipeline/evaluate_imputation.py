class ConfigMismatch(RuntimeError):
    """A checkpoint was made under a different config than the one now loaded."""


def log(msg):
    print(f"[{datetime.datetime.now():%Y-%m-%d %H:%M:%S}] {msg}", flush=True)


# --------------------------------------------------------------------- units
@dataclass
class Unit:
    seed: int
    fold: int
    config: dict

    @property
    def model_type(self):
        return self.config["name"]

    @property
    def num_quantiles(self):
        q = self.config.get("quantiles")
        return len(q) if q is not None else None

    @property
    def run_id(self):
        base = ie.make_run_id(self.seed, self.model_type, self.num_quantiles)
        return f"{base}__fold{self.fold}"

    @property
    def config_hash(self):
        blob = json.dumps(self.config, sort_keys=True, default=str)
        return hashlib.sha256(blob.encode()).hexdigest()[:12]

    @property
    def estimate_key(self):
        # 2- and 3-quantile models of one class differ a lot in cost
        return (self.model_type, self.num_quantiles)

    @property
    def result_dir(self):
        return UNITS_DIR / self.run_id

    @property
    def ckpt_dir(self):
        return CHECKPOINT_DIR / self.run_id

    @property
    def is_done(self):
        # runs.csv is written last, so its existence means the unit is complete
        return (self.result_dir / "runs.csv").exists()


def build_model(unit, epochs=None):
    model_cls = ie.MODEL_CLASSES[unit.model_type]
    config = unit.config
    if epochs is not None:
        # patience=None: with one-epoch fits early stopping could never trigger
        # anyway, and it keeps `patience > epochs` from being an issue
        config = {**config, "epochs": epochs, "patience": None}
    return model_cls(config)


# ------------------------------------------------------------- file helpers
def write_csv_atomic(df, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.{os.getpid()}.tmp")
    df.to_csv(tmp, index=False)
    os.replace(tmp, path)


def _recover(ckpt_dir):
    """Undo a save that was interrupted between its two renames."""
    old = ckpt_dir.with_name(ckpt_dir.name + ".old")
    if not ckpt_dir.exists() and old.exists():
        old.rename(ckpt_dir)


def load_state(unit):
    _recover(unit.ckpt_dir)
    state = dict(NEW_STATE)
    state_file = unit.ckpt_dir / "state.json"
    if state_file.exists():
        state.update(json.loads(state_file.read_text()))
        stored = state["config_hash"]
        if stored is not None and stored != unit.config_hash:
            raise ConfigMismatch(
                f"checkpoint {unit.ckpt_dir} was made with config {stored}, "
                f"but the YAML now hashes to {unit.config_hash}; restore the "
                "config or delete the checkpoint to start this unit over"
            )
    state["config_hash"] = unit.config_hash
    return state


# ------------------------------------------------------------------ failures
def _failure_file(unit):
    return FAILED_DIR / f"{unit.run_id}.json"


def failure_count(unit):
    f = _failure_file(unit)
    return json.loads(f.read_text())["count"] if f.exists() else 0


def record_failure(unit, exc, count=None):
    """Bump the unit's failure count (or set it to `count`); returns the new count."""
    n = count if count is not None else failure_count(unit) + 1
    f = _failure_file(unit)
    f.parent.mkdir(parents=True, exist_ok=True)
    tmp = f.with_name(f"{f.name}.{os.getpid()}.tmp")
    tmp.write_text(
        json.dumps(
            {
                "count": n,
                "when": f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S}",
                "error": repr(exc),
                "traceback": traceback.format_exc(),
            },
            indent=2,
        )
    )
    os.replace(tmp, f)
    return n


def clear_failure(unit):
    _failure_file(unit).unlink(missing_ok=True)


# ----------------------------------------------------------- time estimates
def load_eval_estimates():
    """Slowest measured evaluation per (model type, num quantiles), from the
    runs.csv of every finished unit."""
    est = {}
    for f in UNITS_DIR.glob("*/runs.csv"):
        try:
            row = pd.read_csv(
                f, usecols=["model_type", "num_quantiles", "eval_seconds"]
            ).iloc[0]
        except (ValueError, IndexError):
            continue
        nq = None if pd.isna(row["num_quantiles"]) else int(row["num_quantiles"])
        key = (row["model_type"], nq)
        est[key] = max(est.get(key, 0.0), float(row["eval_seconds"]))
    return est


def eval_reserve_s(unit, env):
    measured = env.eval_estimates.get(unit.estimate_key)
    if measured is None:
        return env.eval_reserve_s
    return max(EVAL_RESERVE_FLOOR_S, EVAL_RESERVE_FACTOR * measured)


def warn_stale_results(units):
    """Finished units whose results were made under a different config."""
    for u in units:
        if not u.is_done:
            continue
        try:
            stored = pd.read_csv(u.result_dir / "runs.csv", usecols=["config_hash"])
            stored = stored["config_hash"].iloc[0]
        except (ValueError, IndexError):
            continue  # results from before hashing
        if isinstance(stored, str) and stored != u.config_hash:
            log(
                f"WARNING {u.run_id}: finished under config {stored}, the YAML now "
                f"hashes to {u.config_hash}; delete {u.result_dir} and {u.ckpt_dir} "
                "to redo it"
            )


def save_checkpoint(model, state, ckpt_dir):
    """Write model + state into a temp dir, then swap it in, so a kill at any
    moment leaves either the old or the new checkpoint intact."""
    tmp = ckpt_dir.with_name(ckpt_dir.name + ".tmp")
    old = ckpt_dir.with_name(ckpt_dir.name + ".old")
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    model.save(tmp / "model")
    (tmp / "state.json").write_text(json.dumps(state))
    if ckpt_dir.exists():
        shutil.rmtree(old, ignore_errors=True)
        ckpt_dir.rename(old)
    tmp.rename(ckpt_dir)
    shutil.rmtree(old, ignore_errors=True)


def collect():
    """Rebuild the combined tables from the finished units' result files.

    Another worker may finish a unit while this one is writing, so it looks
    again after writing and redoes the tables if the set of finished units
    grew. Writes are atomic, but two workers can still interleave; the unit
    directories are the source of truth, so `--collect-only` fixes any miss.
    """
    for _ in range(3):
        done = sorted(p.parent for p in UNITS_DIR.glob("*/runs.csv"))
        if not done:
            return
        for name, out in (("runs.csv", RUNS_FILE), ("metrics.csv", METRICS_FILE)):
            write_csv_atomic(
                pd.concat([pd.read_csv(d / name) for d in done], ignore_index=True),
                out,
            )
        if sorted(p.parent for p in UNITS_DIR.glob("*/runs.csv")) == done:
            break
    log(f"Collected {len(done)} finished units into {RESULTS_DIR}")


# ------------------------------------------------------------------ training
def train(unit, state, env):
    """Train until done or out of time; returns (model, finished)."""
    total_epochs = unit.config["epochs"]

    set_seed(unit.seed)
    model = build_model(unit, epochs=1)  # each fit() call is one epoch
    if state["epochs_done"] > 0:
        model.load(unit.ckpt_dir / "model")
        log(f"{unit.run_id}: resumed at epoch {state['epochs_done']}/{total_epochs}")
    state["sessions"] += 1

    train_set = env.train_set(unit.fold)
    durations, dirty, last_save = [], False, time.time()

    while state["epochs_done"] < total_epochs:
        # leave room for the slowest epoch seen so far (10% slack)
        est = 1.1 * max(durations, default=state["epoch_seconds"])
        if time.time() + est > env.deadline:
            log(
                f"{unit.run_id}: out of time at epoch {state['epochs_done']}/{total_epochs}"
            )
            break

        # reseed per epoch so a resumed run draws the same random numbers an
        # uninterrupted one would
        seed = np.random.SeedSequence([unit.seed, unit.fold, state["epochs_done"]])
        set_seed(int(seed.generate_state(1)[0]))

        start = time.time()
        model.fit(train_set)
        durations.append(time.time() - start)

        state["epochs_done"] += 1
        state["train_seconds"] += durations[-1]
        state["epoch_seconds"] = max(durations)
        state["train_complete"] = state["epochs_done"] >= total_epochs
        dirty = True

        if (
            state["train_complete"]
            or time.time() - last_save >= CHECKPOINT_MIN_INTERVAL_S
        ):
            save_checkpoint(model, state, unit.ckpt_dir)
            dirty, last_save = False, time.time()

    if dirty:
        save_checkpoint(model, state, unit.ckpt_dir)
    return model, state["train_complete"]


# ---------------------------------------------------------------- evaluation
def evaluate_and_write(unit, model, state, env):
    start = time.time()
    val_set, val_index = env.val_set(unit.fold)
    metrics, latency = ie.evaluate_run(
        model,
        val_set,
        val_index,
        unit.num_quantiles,
        env.series_hourly,
        latency_timed_runs=env.latency_runs,
    )
    metrics.insert(0, "run_id", unit.run_id)
    eval_seconds = time.time() - start

    run_row = {
        "run_id": unit.run_id,
        **env.experiment,
        "execution_datetime": datetime.datetime.now(),
        "seed": unit.seed,
        "fold": unit.fold,
        "eval_data": "validation",
        "model_type": unit.model_type,
        "quantiles": unit.config.get("quantiles"),
        "num_quantiles": unit.num_quantiles,
        "train_epochs": state["epochs_done"],
        "train_seconds": state["train_seconds"],
        "train_sessions": state["sessions"],
        "config_hash": unit.config_hash,
        "eval_seconds": eval_seconds,
        **latency,
    }

    # metrics first, runs row last (see Unit.is_done)
    write_csv_atomic(metrics, unit.result_dir / "metrics.csv")
    write_csv_atomic(pd.DataFrame([run_row]), unit.result_dir / "runs.csv")
    return eval_seconds


# --------------------------------------------------------------------- units
def run_unit(unit, env):
    """Advance one unit as far as the time budget allows; True if it finished."""
    if unit.is_done:
        return True

    state = load_state(unit)

    if not state["train_complete"]:
        estimate = (
            state["epoch_seconds"]
            or env.epoch_estimates.get(unit.estimate_key)
            or env.min_start_s
        )
        if env.deadline - time.time() < estimate:
            log(f"{unit.run_id}: not enough time left to start, skipping")
            return False

        model, finished = train(unit, state, env)
        if state["epoch_seconds"]:
            env.epoch_estimates[unit.estimate_key] = state["epoch_seconds"]
        if not finished:
            return False
    else:
        model = build_model(unit)
        model.load(unit.ckpt_dir / "model")

    if env.deadline - time.time() < eval_reserve_s(unit, env):
        log(f"{unit.run_id}: trained, but not enough time left to evaluate")
        return False

    seconds = evaluate_and_write(unit, model, state, env)
    env.eval_estimates[unit.estimate_key] = max(
        env.eval_estimates.get(unit.estimate_key, 0.0), seconds
    )
    log(f"{unit.run_id}: done")
    return True


def run_all(units, env):
    """Process the units in priority order.

    Returns (resumable, abandoned): how many units still have work a later job
    can do, and the run_ids of units that failed too often (or whose checkpoint
    no longer matches the config). A unit that raises never stops the others.
    """
    todo = [u for u in units if not u.is_done]
    # finish units that already have a checkpoint before starting new ones
    todo.sort(key=lambda u: not (u.ckpt_dir / "state.json").exists())

    resumable, abandoned = 0, []
    for unit in todo:
        if failure_count(unit) >= env.max_unit_failures:
            log(f"{unit.run_id}: abandoned after repeated failures, see {FAILED_DIR}")
            abandoned.append(unit.run_id)
            continue
        try:
            finished = run_unit(unit, env)
        except Exception as exc:  # not BaseException: Ctrl-C and sys.exit pass
            fatal = isinstance(exc, ConfigMismatch)
            n = record_failure(unit, exc, env.max_unit_failures if fatal else None)
            log(f"{unit.run_id}: FAILED ({n}/{env.max_unit_failures}): {exc!r}")
            traceback.print_exc()
            gc.collect()
            if n >= env.max_unit_failures:
                abandoned.append(unit.run_id)
            else:
                resumable += 1
            continue
        if finished:
            clear_failure(unit)
        else:
            resumable += 1

    done = sum(u.is_done for u in units)
    log(
        f"{done}/{len(units)} selected units done; "
        f"{resumable} resumable, {len(abandoned)} abandoned"
    )
    return resumable, abandoned


# ------------------------------------------------------------ resume check
def _weights(model):
    """Copies of every tensor in every sub-model's state dict."""
    subs = list(model.models.values()) if hasattr(model, "models") else [model.model]
    return [
        t.detach().cpu().clone() for s in subs for t in s.model.state_dict().values()
    ]


def verify_resume(unit, env):
    """Check that chunked training behaves like training: see the module docstring.

    Passes when (1) one epoch of fit() changes the weights, (2) load() restores
    exactly the saved weights, and (3) fit() after load() changes them again,
    which would fail if the optimizer still pointed at replaced parameters.
    The two validation WAPEs are reported, not asserted: AdamW moments and the
    random stream legitimately differ between the two routes.
    """
    import torch

    def same(a, b):
        return all(torch.equal(x, y) for x, y in zip(a, b))

    def overall_wape(model, val_set, val_index):
        metrics, _ = ie.evaluate_run(
            model,
            val_set,
            val_index,
            unit.num_quantiles,
            env.series_hourly,
            latency_timed_runs=1,
        )
        m = metrics[
            (metrics["day_type"] == "overall")
            & (metrics["volume"] == "all")
            & (metrics["metric"] == "wape")
        ]
        return float(m["value"].iloc[0])

    log(f"verify-resume on {unit.run_id}")
    train_set = env.train_set(unit.fold)
    val_set, val_index = env.val_set(unit.fold)

    set_seed(unit.seed)
    uninterrupted = build_model(unit, epochs=2)
    uninterrupted.fit(train_set)

    set_seed(unit.seed)
    first = build_model(unit, epochs=1)
    initial = _weights(first)
    first.fit(train_set)
    after_one = _weights(first)

    tmp = Path(tempfile.mkdtemp(prefix="verify_resume_"))
    try:
        first.save(tmp / "model")
        resumed = build_model(unit, epochs=1)
        resumed.load(tmp / "model")
        loaded = _weights(resumed)
        resumed.fit(train_set)
        after_two = _weights(resumed)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    checks = {
        "fit() changes weights": not same(after_one, initial),
        "load() restores saved weights": same(loaded, after_one),
        "fit() after load() changes weights": not same(after_two, loaded),
    }
    for name, ok in checks.items():
        log(f"  {'PASS' if ok else 'FAIL'}: {name}")

    wape_full = overall_wape(uninterrupted, val_set, val_index)
    wape_chunked = overall_wape(resumed, val_set, val_index)
    log(
        f"  validation WAPE after 2 epochs: uninterrupted {wape_full:.4f}, "
        f"chunked {wape_chunked:.4f} (difference {wape_chunked - wape_full:+.4f})"
    )
    return 0 if all(checks.values()) else EXIT_FAILED


