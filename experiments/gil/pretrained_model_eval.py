"""Evaluate pretrained imputation models on the calibration set.

Loads each (seed, model) checkpoint, imputes the calibration set, and appends the
results to two long-format tables: one row per run, and one row per
run x subset x metric. Re-running skips runs that are already recorded.
The evaluation pipeline itself lives in `imputation_evaluation_helpers`.

Generated by Claude.
"""

import datetime
from pathlib import Path

import pandas as pd

from uncertainty_aware_planner.data.config import load_config, load_yaml
from uncertainty_aware_planner.data.cube import load_cube
from uncertainty_aware_planner.data.pypots_arrays import build_pypots_set
from uncertainty_aware_planner.utils.util_functions import set_seed
from uncertainty_aware_planner.evaluation import imputation_evaluation_helpers as ie

# ---------------------------------------------------------------- constants
CONFIG_DIR = Path("configs/imputation_models")
CONFIG_FILES = [
    "dlinear_imputation_quantile.yaml",
    "dlinear_imputation_quantile_median.yaml",
    "timesnet_imputation_quantile_median.yaml",
    "dlinear_imputation_baseline.yaml",
]
PUBLIC_DATA_CONFIG_FILE = Path("configs/data.yaml")
SPLIT_CONFIG_FILE = Path("configs/splits.yaml")

DATA_DIR = Path("experiments/gil/data")
MODEL_DIRECTORY = Path("experiments/gil/models")
RESULTS_DIR = Path("results/imputation")
RESULTS_STEM = "pretrained_model_eval_py_execution_1"
RUNS_FILE = RESULTS_DIR / f"{RESULTS_STEM}_runs.csv"  # one row per run
METRICS_FILE = (
    RESULTS_DIR / f"{RESULTS_STEM}_metrics.csv"
)  # long: run x subset x metric
REPO_DIR = Path(__file__).resolve().parent

SEEDS = [86400, 4, 42]

# (model name, num quantiles) -> subdirectory suffix of the pretrained checkpoint
CHECKPOINT_SUBDIRS = {
    ("DLinear_Imputation_Baseline", None): "dlinear_baseline",
    ("DLinear_Imputation_Quantile", 2): "dlinear_quantile_interval_only",
    ("DLinear_Imputation_Quantile", 3): "dlinear_quantile",
    ("TimesNet_Imputation_Quantile", 3): "timesnet",
}


# ------------------------------------------------------------------- helpers
def load_completed_runs():
    """run_ids in the runs table.

    A run's runs row is written after its metric rows, so metric rows without
    one come from an interrupted run; they are dropped so the run can be redone.
    """
    done = set()
    if RUNS_FILE.exists():
        done = set(pd.read_csv(RUNS_FILE, usecols=["run_id"])["run_id"])
    if METRICS_FILE.exists():
        metrics = pd.read_csv(METRICS_FILE)
        keep = metrics["run_id"].isin(done)
        if not keep.all():
            metrics[keep].to_csv(METRICS_FILE, index=False)
    return done


def append_csv(df, path):
    df.to_csv(path, mode="a", header=not path.exists(), index=False)


# ---------------------------------------------------------------------- main
def main():
    series_hourly = ie.load_series_hourly(DATA_DIR)
    completed = load_completed_runs()
    configs = [load_yaml(CONFIG_DIR / f) for f in CONFIG_FILES]

    # fail now, not after loading data and the first few models
    for config in configs:
        quantiles = config.get("quantiles")
        key = (config["name"], len(quantiles) if quantiles is not None else None)
        ie.check_supported(*key)
        if key not in CHECKPOINT_SUBDIRS:
            raise ValueError(f"no pretrained checkpoint directory known for {key}")

    cfg = load_config()
    cube = load_cube(cfg)
    masks = pd.read_parquet("data/processed/eval_masks.parquet")

    # independent of seed and model, so built once
    calib_set, calib_index = build_pypots_set(cube, cfg, "calib", masks=masks)

    experiment_dict = ie.experiment_metadata(
        REPO_DIR, PUBLIC_DATA_CONFIG_FILE, SPLIT_CONFIG_FILE
    )

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    for seed in SEEDS:
        for config in configs:
            model_type = config["name"]
            quantiles = config.get("quantiles")
            num_quantiles = len(quantiles) if quantiles is not None else None

            run_id = ie.make_run_id(seed, model_type, num_quantiles)
            if run_id in completed:
                print(f"Skipping seed={seed}, {model_type}, q={num_quantiles} (done)")
                continue

            set_seed(seed)

            # load
            key = (model_type, num_quantiles)
            model = ie.MODEL_CLASSES[model_type](config)
            model.load(MODEL_DIRECTORY / f"seed_{seed}_{CHECKPOINT_SUBDIRS[key]}")

            metrics, latency = ie.evaluate_run(
                model, calib_set, calib_index, num_quantiles, series_hourly
            )
            metrics.insert(0, "run_id", run_id)

            run_row = {
                "run_id": run_id,
                **experiment_dict,
                "execution_datetime": datetime.datetime.now(),
                "seed": seed,
                "eval_data": "calibration",
                "model_type": model_type,
                "quantiles": quantiles,
                "num_quantiles": num_quantiles,
                **latency,
            }

            # metrics first, runs row last: a run counts as done only once its
            # runs row exists (see load_completed_runs)
            append_csv(metrics, METRICS_FILE)
            append_csv(pd.DataFrame([run_row]), RUNS_FILE)


if __name__ == "__main__":
    main()
